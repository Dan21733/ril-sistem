# ---------------------------------------------------------------------------
# Database uji disposable, terpisah dari produksi (2026-10-02, item #2).
# ---------------------------------------------------------------------------
#
# Test runner Django membuat/menghapus database `test_*` di server yang
# dituju DATABASE_URL. Tanpa guard, `manage.py test` memakai DATABASE_URL
# dari .env yang bisa menunjuk database bersama/produksi: tidak menghapus
# data produksi, tetapi membuat database uji di server produksi dan
# membebaninya. Pengujian PostgreSQL karena itu wajib memakai database
# disposable terpisah yang disetujui pemilik:
#
# - POS_TEST_DATABASE_URL: koneksi database disposable (mis. pos_test di
#   service CI atau database uji milik tim). Bila diset saat `test`
#   berjalan, koneksi inilah yang dipakai, bukan DATABASE_URL.
# - POS_TEST_RUN=1: penanda bahwa DATABASE_URL saat ini SUDAH disposable
#   (dipasang CI dan tools/run_pg_tests.py).
#
# Tanpa salah satunya, `manage.py test` dengan engine PostgreSQL berhenti
# dengan pesan di bawah. SQLite (`DATABASE_URL='sqlite://:memory:'`) tidak
# kena guard: smoke test tetap jalan tanpa database bisnis.
POS_TEST_DATABASE_URL = os.getenv("POS_TEST_DATABASE_URL", "").strip()
POS_TEST_RUN = os.getenv("POS_TEST_RUN", "").strip() == "1"

if "test" in sys.argv and "--help" not in sys.argv and "-h" not in sys.argv:
    if POS_TEST_DATABASE_URL:
        DATABASES["default"] = dj_database_url.parse(POS_TEST_DATABASE_URL)
    elif "postgres" in DATABASES["default"].get("ENGINE", "") and not POS_TEST_RUN:
        raise RuntimeError(
            "Pengujian PostgreSQL membutuhkan database disposable yang "
            "terpisah dari produksi. Set POS_TEST_DATABASE_URL ke koneksi "
            "database uji (minta ke pemilik database), atau set "
            "POS_TEST_RUN=1 bila DATABASE_URL saat ini sudah disposable. "
            "Lihat README bagian Verifikasi aman. Tanpa database bisnis, "
            "pakai DATABASE_URL='sqlite://:memory:' dengan kredensial dummy."
        )

