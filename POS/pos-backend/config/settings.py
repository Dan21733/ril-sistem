def _required_env(name):
    """Ambil variabel wajib, atau berhenti dengan pesan yang menunjuk berkasnya.

    Pesan bawaan Django ("SECRET_KEY environment variable is required") benar
    tapi tidak memberi tahu di mana nilainya diharapkan berada; insiden
    2026-09-29 di mesin client membuktikan itu menghabiskan satu putaran tanya
    jawab. Karena itu pesannya menyebut berkas .env dan penyiapnya.
    """
    value = (os.getenv(name) or "").strip()

    if not value:
        raise RuntimeError(
            f"{name} belum diisi. Isi berkas {BASE_DIR / '.env'} "
            "(lihat pos-backend/.env.example), atau jalankan dari folder "
            "pos-backend: venv\\Scripts\\python.exe tools\\setup_env.py"
        )

    return value


